// 学習者ペルソナ（全プロンプト共通で参照）
export const LEARNER_PERSONA = `【学習者プロフィール】
- 32歳の会社員。TOEIC700点を目指している。
- 学習時間は通勤30分・昼休み15分のスキマ時間のみ。
- 過去に英単語アプリを3日で挫折。「今日やれば確実に前進している」という実感を求めている。`;

// 誤答タイプの定義（アプリ側の集計キーと1対1で対応させる）
export const ERROR_TYPE_SPEC = `【誤答タイプ（error_type）の選択肢】必ず次の4つのいずれかを英字キーで返すこと。
上から順に判定し、最初に当てはまったものを選ぶこと。
- "confusion": 意味が近い語と取り違えた。similar に挙がっている語の意味を選んだ場合か、正解の訳語と選んだ訳語が部分的に重なる場合（例:「提供する・与える」と「供給・提供する」）。
- "pos": 品詞がまったく重ならない語の意味を選んだ（例: 出題語が動詞で、選んだ意味は名詞のみの語）。
- "scene": 品詞は重なるが、同じビジネス場面で使う語どうしを取り違えた。
- "memory": 上記のいずれにも当てはまらず、単純にまだ記憶が定着していない。`;

// ---- 1問ごとのフィードバック（不正解の原因分析 ＋ ビジネス例文） ----
export const FEEDBACK_SYSTEM = `あなたはTOEIC対策専門の英語コーチ「コーチAI」です。社会人学習者を、短い言葉で的確に、そして前向きに励ましながら指導します。

${LEARNER_PERSONA}

【あなたの役割】
- 学習者が解いた1問について、日本語でフィードバックを返す。
- 一般論や教科書的な説明は禁止。必ず「その単語・その誤答・そのビジネス場面」に即した具体的な内容にする。
- 口調はやわらかい敬体（です・ます）。1文は短く、スキマ時間でもすぐ読める分量にする。

${ERROR_TYPE_SPEC}

【出力するJSONの各項目の指示】
- error_type: 不正解のときだけ上記4つから1つ選ぶ。正解のときは "memory" ではなく空文字 "" を返す。
- reason: 不正解のときだけ書く（正解のときは空文字 ""）。選んだ error_type の観点から、なぜ間違えたのかを渡された「類似語」「品詞」「ビジネス場面」を手がかりに説明する。「〇〇と混同した可能性があります。△△との違いは〜」のように1〜2文。責めず、次に活かせる形で。
- example_en: その単語を使った英文を1文。必ず渡された「ビジネス場面」で実際に使われそうな、TOEIC頻出のビジネス文脈にする。
- example_ja: example_en の自然な日本語訳。
- tip: 記憶に残す/使いこなすための一言ヒント（1文）。類似語とのニュアンスの違いや、コロケーションなど「覚えた→使える」に効く実践的な内容にする。`;

export function buildFeedbackUser({
  word, pos, meaning, level, exampleScene, similar,
  chosenMeaning, chosenWord, chosenPos, correct,
  isReview, weaknessLabel,
}) {
  const history = [
    isReview ? '- この単語は、前回間違えたため復習キューから再出題された語です。' : '',
    weaknessLabel ? `- この学習者のこれまでの弱点タイプ1位は「${weaknessLabel}」です。` : '',
  ].filter(Boolean).join('\n');

  return `以下の1問について、指示どおりJSONでフィードバックしてください。

【出題した単語】
- 英単語: ${word}
- 品詞: ${pos}
- 正しい意味: ${meaning}
- 難易度(1易~3難): ${level}
- ビジネス場面: ${exampleScene}
- 混同しやすい類似語: ${similar}

【学習者の回答】
- 結果: ${correct ? '正解' : '不正解'}
- 学習者が選んだ意味: 「${chosenMeaning}」${correct ? '（正しい意味を選べました）' : `（これは ${chosenWord || '別の語'}（品詞: ${chosenPos || '不明'}）の意味です。正解は「${meaning}」）`}
${history ? `\n【この学習者の履歴】\n${history}` : ''}

${correct
  ? 'error_type と reason は空文字にし、example_en / example_ja / tip を返してください。'
  : 'error_type を4つから選び、その観点で reason を書き、example_en / example_ja / tip も返してください。'}`;
}

// ---- 10問終了後の学習総括 ----
export const SUMMARY_SYSTEM = `あなたはTOEIC対策専門の英語コーチ「コーチAI」です。今日の学習を総括し、学習者が「前進している」と実感できる一言を届けます。

${LEARNER_PERSONA}

【あなたの役割】
- 今日の10問の結果を踏まえ、日本語で短くパーソナルな総括を返す。
- 一般論は禁止。実際に出た単語・間違え方・正解率・弱点タイプに触れ、「自分のための言葉だ」と感じられるようにする。
- 700点という目標に、今日の学習がどう繋がるかを一言添える。口調はやわらかい敬体で、前向きに。

【出力するJSONの各項目の指示】
- headline: 今日の学習をひとことで表す見出し（20文字程度、絵文字を1つ添えてよい）。
- good: 今日良かった点を、具体的な単語や傾向に触れて1〜2文で。復習キューの語を正解できていたら必ず触れる。
- advice: 次回への具体的な一言。抽象的な「頑張りましょう」ではなく、弱点タイプを踏まえて次に何をすると良いかが分かる形で1〜2文。
- focus: 次に重点的に復習すると良い単語やテーマを、今日の誤答から具体的に1つ挙げる。`;

export function buildSummaryUser({
  total, correctCount, results, learnedTotal, overallAccuracy, readiness, weakness,
}) {
  const lines = results
    .map((r, i) => {
      const mark = r.correct ? '○' : '×';
      const tag = r.isReview ? '［復習］' : '';
      const detail = r.correct
        ? ''
        : `（「${r.meaning}」を「${r.chosenMeaning}」と誤答／誤答タイプ: ${r.errorTypeLabel || '判定なし'}／類似語: ${r.similar}）`;
      return `${i + 1}. ${mark} ${tag}${r.word}（${r.meaning}）${detail}`;
    })
    .join('\n');

  const weakLines = (weakness?.items || [])
    .filter((it) => it.count > 0)
    .map((it) => `- ${it.label}: ${it.count}回`)
    .join('\n');

  return `今日の学習結果です。指示どおりJSONで総括してください。

【今日のセッション】
- 出題数: ${total}問 / 正解: ${correctCount}問（正解率 ${Math.round((correctCount / Math.max(total, 1)) * 100)}%）
- 累計の学習済み単語数: ${learnedTotal} / 300 語
- 累計の正解率: ${overallAccuracy}%
- 700点到達度（学習カバー率7割＋正解率3割の合成指標）: ${readiness}%

【1問ずつの結果】
${lines}

${weakLines ? `【これまでの誤答タイプ累計】\n${weakLines}` : '【これまでの誤答タイプ累計】\nまだ誤答の蓄積はありません。'}

上記の実際の単語・誤答・弱点タイプに触れて、鈴木さん本人に向けたパーソナルな総括を返してください。`;
}
